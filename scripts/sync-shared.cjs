#!/usr/bin/env node
// 两仓共享文件同步：以 AgentBrowserBridge-CrossBrowser 为源，复制到 GcWebAuto，并在两边写入 shared-files.json（内容指纹）。
// 用法：node scripts/sync-shared.cjs [GcWebAuto 路径]
// 两边的 tests/shared-sync.test.cjs 会校验指纹：只改了一边而没同步，测试就会失败。
// 实现不同的核心文件（client/concurrency/interaction 等）不在此列，靠两边共用的 tests/hardening.test.cjs 保证行为一致。
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const SRC = path.resolve(__dirname, '..');
const DST = path.resolve(process.argv[2] || 'C:/GkDesktop/GitProjects/GcWebAuto');
const SHARED = [
  'lib/cdp/advanced.js',
  'lib/cdp/element-ui.js',
  'lib/cdp/locator.js',
  'lib/cdp/runner.js',
  'lib/cdp/snapshot.js',
  'learnings/etax-gd',
  'learnings/k3cloud',
  'tests/hardening.test.cjs',
  'tests/egolite.test.cjs',
  'tests/shared-sync.test.cjs',
  'cli/smoke-k3.cjs',
];

const walk = (root, rel) => {
  const abs = path.join(root, rel);
  if (fs.statSync(abs).isFile()) return [rel.replace(/\\/g, '/')];
  return fs.readdirSync(abs).flatMap((n) => walk(root, path.join(rel, n)));
};
const norm = (buf) => buf.toString('utf8').replace(/\r\n/g, '\n');
const hash = (file) => crypto.createHash('sha256').update(norm(fs.readFileSync(file))).digest('hex');

const files = SHARED.flatMap((p) => walk(SRC, p)).sort();
for (const f of files) {
  const target = path.join(DST, f);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, norm(fs.readFileSync(path.join(SRC, f))), 'utf8');
}
const manifest = {
  note: 'Generated by AgentBrowserBridge-CrossBrowser/scripts/sync-shared.cjs. Do not edit by hand; edit the source repo and re-run the sync.',
  files: Object.fromEntries(files.map((f) => [f, hash(path.join(SRC, f))])),
};
for (const root of [SRC, DST]) fs.writeFileSync(path.join(root, 'shared-files.json'), JSON.stringify(manifest, null, 2) + '\n', 'utf8');
console.log(`synced ${files.length} shared files -> ${DST}`);
